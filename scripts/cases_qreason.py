#!/usr/bin/env python3
"""Live examples for LLM query expansion (LOG 2026-10-26 13:46 rule): research/cases/query_reasoning_dev.md.

Per condition (2a_current, 1a), dev: "before" = hybrid of variant q, "after" = the rule-6
choice (or the best-on-train variant if rule 6 kept q). Topics split into improved / worsened
by hybrid nDCG@10; 2 drawn from each with random.Random(20260921) over sorted qids.

    python3 cases_qreason.py --out ../research/cases/query_reasoning_dev.md
"""
import argparse
import json
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bm25s_run import ndcg_fn  # noqa: E402
from dense_index import T1, T2  # noqa: E402
from gold_categories import fetch  # noqa: E402
from hybrid import Query, qrels_for, read_run, system  # noqa: E402
from llm_expand import inputs as llm_inputs, key_of  # noqa: E402
from qexp_search import load_gen  # noqa: E402

R = "../research/runs_v13"
CONDS = [("2a_current", 2, "qexp/t2", "hybrid_2a_current.json", "llm/t2", "select/rule6_2a_current.json"),
         ("1a", 1, "qexp/t1", "hybrid_1a.json", "llm/t1", "select/rule6_1a.json")]


def short(t, n=300):
    t = " ".join((t or "").split())
    return t[:n] + (" …" if len(t) > n else "")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="../../reteco_data_v11")
    ap.add_argument("--kit", default="../../RETECO/starter_kit")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    ndcg = ndcg_fn(a.kit)
    L = ["# LLM query expansion — dev examples (week 5)", "",
         "Generated by `scripts/cases_qreason.py`. Selection rule written before any result was seen "
         "(LOG 2026-10-26 13:46): per condition, dev topics split into improved / worsened (hybrid nDCG@10 of "
         "the expanded system vs the plain query); 2 drawn from each with `random.Random(20260921)` over sorted "
         "topic ids. LLM: Qwen3-4B-Instruct-2507 (AWQ 4-bit), temperature 0; prompts in "
         "`research/runs_v13/llm/t*/meta.json`. Ranks are 1-based positions in the hybrid list (— = not in its fusion pool, "
         "BM25 top-k ∪ dense top-k). Labels/judgements below are the assistant's preliminary reading.", ""]
    for cond, track, qdir, hrep, ldir, sel in CONDS:
        s = json.load(open(os.path.join(R, sel)))
        after = s["chosen"] if s["adopted"] else s["best_on_train"]
        rep = json.load(open(os.path.join(R, qdir, hrep)))["conditions"]
        cfg_b, cfg_a = (rep[f"{cond}__{v}"]["systems"]["linear*"]["cfg"] for v in ("q", after))
        gen = {p: load_gen(os.path.join(R, ldir), p) for p in ("reason", "hyde")}
        body = {(dm, sp, qid): b for dm, sp, qid, b in llm_inputs(a.data, track, cond)}
        rows = []
        for dom in (T1 if track == 1 else T2):
            gold = qrels_for(a.data, track, dom, "dev", cond)
            runs = {}
            for v in ("q", after):
                pre = f"t{track}_{dom}_dev_{cond}__{v}.tsv"
                runs[v] = (read_run(os.path.join(R, qdir, "bm25/runs", pre)), read_run(os.path.join(R, qdir, "dense/runs", pre)))
            for qid, g in gold.items():
                lb = system(Query(runs["q"][0].get(qid, []), runs["q"][1].get(qid, [])), cfg_b)
                la = system(Query(runs[after][0].get(qid, []), runs[after][1].get(qid, [])), cfg_a)
                rows.append((dom, qid, g, lb, la, ndcg(lb, g, 10), ndcg(la, g, 10)))
        up = sorted([r for r in rows if r[6] > r[5]], key=lambda r: r[1])
        down = sorted([r for r in rows if r[6] < r[5]], key=lambda r: r[1])
        rng = random.Random(20260921)
        pick = [("improved", r) for r in rng.sample(up, min(2, len(up)))] + \
               [("worsened", r) for r in rng.sample(down, min(2, len(down)))]
        L += [f"## {cond}: plain query vs `{after}`" + ("" if s["adopted"] else " (best on train; rule 6 kept the plain query)"), "",
              f"Dev topics: {len(rows)}; improved {len(up)}, worsened {len(down)}, unchanged {len(rows) - len(up) - len(down)}.", ""]
        for i, (lab, (dom, qid, g, lb, la, nb, na)) in enumerate(pick, 1):
            k = body.get((dom, "dev", qid))
            texts = fetch(a.data, track, dom, set(g))
            L += [f"### {cond} {i} — {lab} ({dom}): nDCG@10 {nb:.3f} → {na:.3f}", "",
                  f"**Query (as given to the LLM).** {short(k, 700)}", ""]
            for p, code in (("reason", "r"), ("hyde", "h")):
                if code in after.split("+"):
                    L += [f"**Generated `{p}`.** {short(gen[p].get(key_of(p, k), ''), 900)}", ""]
            L += ["| gold document (first 300 chars) | rank before | rank after |", "| --- | --- | --- |"]
            for d in sorted(g):
                rb = lb.index(d) + 1 if d in lb else "—"
                ra = la.index(d) + 1 if d in la else "—"
                L.append(f"| {short(texts.get(d, ''), 300).replace('|', '/')} | {rb} | {ra} |")
            L.append("")
    open(a.out, "w").write("\n".join(L) + "\n")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
