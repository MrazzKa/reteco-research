#!/usr/bin/env python3
"""Four dev examples, H0 (week-4 history hybrid) vs Hb (rule-11 LLM hybrid); rule in LOG 2026-11-02 14:25.

    python3 cases_history.py --data ../../reteco_data_v11 --kit ../../RETECO/starter_kit \
        --runs ../research/runs_v13 --out ../research/cases/history_llm_dev.md
"""
import argparse
import json
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bm25s_run import ndcg_fn  # noqa: E402
from dense_index import T2  # noqa: E402
from gold_categories import fetch  # noqa: E402
from hybrid import Query, read_run  # noqa: E402
from llm_expand import history_body, key_of  # noqa: E402
from qexp_search import load_gen  # noqa: E402
from tie_study import fused, order  # noqa: E402
from week1_run import load_qrels  # noqa: E402


def ranked(rep_path, cond, dom):
    rep = json.load(open(rep_path))
    hc = rep["conditions"][cond]
    bm = read_run(os.path.join(rep["bm25"], f"t2_{dom}_dev_{cond}.tsv"))
    de = read_run(os.path.join(rep["dense"], f"t2_{dom}_dev_{hc['dense_condition']}.tsv"))
    cfg = hc["systems"]["linear*"]["cfg"]
    return {q: [d for d, _ in order(fused(Query(bm[q], de.get(q, [])), cfg))] for q in bm}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", required=True)
    ap.add_argument("--kit", required=True)
    ap.add_argument("--runs", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    os.chdir(os.path.dirname(os.path.abspath(__file__)))
    ndcg = ndcg_fn(a.kit)
    R = a.runs
    gen = load_gen(os.path.join(R, "llm", "t2"), "reason")
    imp, wor, info = [], [], {}
    for dom in T2:
        d = os.path.join(a.data, "track2_recor", dom)
        gold = load_qrels(os.path.join(d, "qrels_dev.txt"))
        bench = json.load(open(os.path.join(d, "benchmark_dev.json"), encoding="utf-8"))
        bench = [bench] if isinstance(bench, dict) else bench
        turns = {f"{c['id']}_turn_{t['turn_id']}": t for c in bench for t in c["turns"]}
        h0 = ranked(f"{R}/hist/t2/hybrid_h0.json", "2a_history", dom)
        hb = ranked(f"{R}/hist/t2/hybrid.json", "2a_hist3qa__q+r+h", dom)
        for q in sorted(gold):
            if int(q.rsplit("_turn_", 1)[1]) < 2:
                continue
            b, c = ndcg(h0.get(q, []), gold[q], 10), ndcg(hb.get(q, []), gold[q], 10)
            info[(dom, q)] = (b, c, turns[q], gold[q], h0.get(q, []), hb.get(q, []))
            (imp if c > b else wor if c < b else []).append((dom, q))
    rng = random.Random(20260921)
    picks = [("improved", x) for x in rng.sample(sorted(imp), 2)] + [("worsened", x) for x in rng.sample(sorted(wor), 2)]
    L = ["# Track 2 with history: week-4 hybrid (H0) vs LLM with earlier answers (Hb), dev", "",
         f"Rule: LOG 2026-11-02 14:25 (seed 20260921, turns ≥ 2; {len(imp)} improved, {len(wor)} worsened). "
         "Generated by `scripts/cases_history.py`.", ""]
    for kind, (dom, q) in picks:
        b, c, t, g, r0, r1 = info[(dom, q)]
        body = history_body(t, True)
        reason = gen.get(key_of("reason", body), "")
        docs = fetch(a.data, 2, dom, set(g))
        L += [f"## {kind}: {dom} / {q} — nDCG@10 {b:.3f} → {c:.3f}", "",
              f"**Current question:** {t['query']}", "",
              f"**History seen by the LLM (first 400 chars):** {body.split(chr(10) + chr(10), 1)[-1][:400]}", "",
              f"**LLM reason (first 400 chars):** {reason[:400]}", ""]
        for doc in sorted(g):
            rk0 = r0.index(doc) + 1 if doc in r0 else None
            rk1 = r1.index(doc) + 1 if doc in r1 else None
            L += [f"- gold, rank {rk0 or '>pool'} → {rk1 or '>pool'}: {' '.join(docs.get(doc, '').split())[:250]}"]
        L.append("")
    open(a.out, "w").write("\n".join(L))
    print("wrote", a.out)


if __name__ == "__main__":
    main()
