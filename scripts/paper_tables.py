def t6_domains(a, R, out, ndcg):
    sc = jload(os.path.join(R, "submit_check_1116.json"))
    subdir = os.path.join(R, "submit", "dev_1116") if os.path.isdir(os.path.join(R, "submit", "dev_1116", "2a_history_rr")) \
        else os.path.join(R, "submit", "dev")
    runs = {"1a": ("1a", T1, 1, "qrels_{split}.txt"), "1b": ("1b", T1, 1, "qrels_steps_{split}.txt"),
            "2a": ("2a_history_rr", T2, 2, "qrels_{split}.txt")}
    per = {}
    for sub, (v, doms, tr, qn) in runs.items():
        if sc and v in sc and "per_domain" in sc[v]:
            per[sub] = {d: sc[v]["per_domain"][d] for d in doms}
            src = "submit_check_1116.json"
        else:
            pt = per_topic(os.path.join(subdir, v, "{dom}.txt"), a.data, ndcg, doms, track=tr, qrels_name=qn)
            per[sub] = {d: sum(x) / len(x) for d, x in pt.items()}
            src = os.path.relpath(subdir, a.root)
        for d, x in per[sub].items():
            put(f"domain.{sub}.{d}", x)
        put(f"domain.{sub}.macro", sum(per[sub].values()) / len(per[sub]))
    if sc is None:
        print(f"NOTE: submit_check_1116.json missing — per-domain numbers recomputed from {src}")
    rows = []
    for d in T1:
        rows.append([esc(d), f(per["1a"][d]), f(per["1b"][d])])
    rows += ["MID", ["macro", f(sum(per["1a"].values()) / 13), f(sum(per["1b"].values()) / 13)]]
    table(out, "t6_domains_t1.tex", "Dev nDCG@10 of the Track-1 main runs per domain.", "tab:domains-t1", "lcc",
          ["Domain", "1a", "1b"], rows)
    rows = []
    for grp, lab in ((True, "BRIGHT"), (False, "StackExchange")):
        ds = [d for d in T2 if (d in BRIGHT_DOMAINS) == grp]
        for d in ds:
            rows.append([esc(d), lab, f(per["2a"][d])])
        m = sum(per["2a"][d] for d in ds) / len(ds)
        put(f"domain.2a.{lab}_mean", m)
        rows += [[f"\\textit{{mean {lab}}}", "", f(m)], "MID"]
    rows += [["macro", "", f(sum(per["2a"].values()) / 11)]]
    table(out, "t6_domains_t2.tex", "Dev nDCG@10 of the 2a main run (\\texttt{UA\\_2a\\_history\\_rr}) per domain.",
          "tab:domains-t2", "llc", ["Domain", "Source", "2a"], rows)


