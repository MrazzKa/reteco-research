def t3_answers(a, R, out, ndcg):
    a2 = jload(os.path.join(R, "a2", "report.json"))
    r14b = jload(os.path.join(R, "select", "rule14b_train.json"))
    if not a2:
        return placeholder(out, "t3_answers.tex", "a2/report.json missing")
    m0bd = jload(os.path.join(R, "a2", "m0_dev_breakdown.json"))
    m0row = None
    if m0bd:
        m0row = next((v for k, v in m0bd.items() if "M0" in k), None) or next(iter(m0bd.values()))
    # per-topic dev for paired CIs against M0
    S = os.path.join(R, "submit", "dev")
    pt = {"ref": per_topic(os.path.join(S, "2a_history", "{dom}.txt"), a.data, ndcg, T2),
          "gen": per_topic(os.path.join(R, "a2", "sub_gen", "dev", "2a_history", "{dom}.txt"), a.data, ndcg, T2),
          "m0": per_topic(os.path.join(R, "a2", "sub_m0dev", "2a_history", "{dom}.txt"), a.data, ndcg, T2)}
    cis = {}
    if pt["m0"]:
        put("ans.m0.dev_recomputed", macro(pt["m0"]))
        for k in ("ref", "gen"):
            if pt[k]:
                cis[k] = bootstrap(pt[k], pt["m0"])
                put_ci(f"ans.{k}_minus_m0.dev", cis[k])
    tr, dv = a2["trainsub"], a2["dev"]
    spec = [("ref", "Reference answers (released history)", tr["main, reference answers"], dv["main, reference answers"]),
            ("gen", "LLM-written answers", tr["main, LLM-written answers"], dv["main, LLM-written answers"]),
            ("m0", "No answers, same pipeline (M0)", r14b["M0 main pipeline, no answers"] if r14b else None, m0row),
            ("h0q", "No answers, answer-free run (H0q+RE)", tr["no answers (rule 14, H0q+RE)"], dv["no answers (rule 14, H0q+RE)"]),
            ("cur", "Current turn only (B)", tr["current turn B"], dv["current turn B"])]
    rows = []
    for k, lab, t_, d_ in spec:
        g = (d_ or {}).get("groups", {})
        dmac = d_["macro"] if d_ else None
        if k == "m0" and dmac is None and pt["m0"]:
            dmac = macro(pt["m0"])
        put(f"ans.{k}.train", t_["macro"] if t_ else None)
        put(f"ans.{k}.dev", dmac)
        put(f"ans.{k}.dev_recycled", g.get("recycled_gold", {}).get("ndcg10"))
        put(f"ans.{k}.dev_new", g.get("new_gold", {}).get("ndcg10"))
        rows.append([esc(lab), f(t_["macro"] if t_ else None), f(dmac),
                     f(g.get("recycled_gold", {}).get("ndcg10")), f(g.get("new_gold", {}).get("ndcg10")),
                     fci(cis[k]) if k in cis else "--"])
    if not m0bd:
        print("NOTE: a2/m0_dev_breakdown.json missing — M0 dev groups shown as '--'")
    nrec = dv["main, reference answers"]["groups"]["recycled_gold"]["n"]
    nnew = dv["main, reference answers"]["groups"]["new_gold"]["n"]
    table(out, "t3_answers.tex", "What the 2a main pipeline (without reranker) owes to the reference answers in "
          "\\texttt{conversation\\_history}. Same frozen pipeline; only the earlier answers differ (M0: none). "
          f"Recycled: later turns whose gold overlaps an earlier turn's gold ({nrec} dev turns); new: later turns with "
          f"only new gold ({nnew}). Group columns are means over turns.",
          "tab:app-answers", "lccccc", ["History given to the pipeline", "Train", "Dev", "Dev recycled", "Dev new",
                                    "Dev $-$ M0 [95\\% CI]"], rows, star=True)


