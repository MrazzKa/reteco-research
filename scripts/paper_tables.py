def jload(p):
    return json.load(open(p, encoding="utf-8")) if os.path.exists(p) else None


def put(key, v):
    if v is not None:
        N[key] = round(v, 4) if isinstance(v, float) else v


def put_ci(key, b):
    """bootstrap dict {diff, ci95} -> key, key.ci_lo, key.ci_hi"""
    if b:
        put(key, b["diff"])
        put(key + ".ci_lo", b["ci95"][0])
        put(key + ".ci_hi", b["ci95"][1])


def f(v, sign=False):
    """Round half-up (Decimal), not banker's / binary-float rounding: 0.5475 -> 0.548."""
    if v is None or v != v:
        return "--"
    x = Decimal(repr(float(v))).quantize(Decimal(1).scaleb(-D), rounding=ROUND_HALF_UP)
    if x == 0:
        x = abs(x)
    s_ = f"{x:.{D}f}"
    return ("+" + s_ if x >= 0 else s_) if sign else s_


def fci(b, sign=True):
    """bootstrap dict -> '+0.012 [+0.004, +0.020]'; None -> '--'"""
    if not b:
        return "--"
    return f"{f(b['diff'], sign)} [{f(b['ci95'][0], sign)}, {f(b['ci95'][1], sign)}]"


def fv_ci(v, ci):
    return f"{f(v)} [{f(ci[0])}, {f(ci[1])}]" if ci else f(v)


def esc(s):
    s = str(s)
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("_", r"\_"), ("#", r"\#"),
                 ("~", r"$\sim$"), ("≤", r"$\le$"), ("≥", r"$\ge$"), ("≈", r"$\approx$"), ("−", "-"),
                 ("→", r"$\rightarrow$"), ("×", r"$\times$"), ("–", "--")):
        s = s.replace(a, b)
    return s


def tt(s):
    return r"\texttt{" + esc(s) + "}"


def table(out, name, caption, label, cols, header, rows, note=None, star=False):
    env = "table*" if star else "table"
    L = [f"% generated by scripts/paper_tables.py — do not edit by hand", rf"\begin{{{env}}}[t]", r"\centering", r"\small",
         rf"\begin{{tabular}}{{{cols}}}", r"\toprule", " & ".join(header) + r" \\", r"\midrule"]
    for r in rows:
        if r == "MID":
            L.append(r"\midrule")
        else:
            L.append(" & ".join(r) + r" \\")
    L += [r"\bottomrule", r"\end{tabular}"]
    if note:
        L.append(r"\par\smallskip{\footnotesize " + note + "}")
    L += [rf"\caption{{{caption}}}", rf"\label{{{label}}}", rf"\end{{{env}}}", ""]
    open(os.path.join(out, name), "w", encoding="utf-8").write("\n".join(L))


def placeholder(out, name, why):
    open(os.path.join(out, name), "w", encoding="utf-8").write(
        f"% generated by scripts/paper_tables.py — PLACEHOLDER: {why}\n")


def per_topic(run_path_fmt, data, kit_ndcg, doms, split="dev", track=2, qrels_name="qrels_{split}.txt"):
    """{dom: [nDCG@10 per judged topic, sorted qid]} from per-domain run files (official nDCG)."""
    sub = "track1_tempo" if track == 1 else "track2_recor"
    out = {}
    for dom in doms:
        p = run_path_fmt.format(dom=dom)
        if not os.path.exists(p):
            return None
        run = read_run(p)
        gold = load_qrels(os.path.join(data, sub, dom, qrels_name.format(split=split)))
        out[dom] = [kit_ndcg([d for d, _ in run.get(q, [])], gold[q], 10) for q in sorted(gold)]
    return out


def macro(pt):
    return sum(sum(v) / len(v) for v in pt.values()) / len(pt)


