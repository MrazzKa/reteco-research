def t2_ablation(R, out):
    ab = jload(os.path.join(R, "ablation_1110.json"))
    if not ab:
        return placeholder(out, "t2_ablation.tex", "ablation_1110.json missing")
    names = {"1a": "1a", "1b": "1b", "2a_current": "2a, current turn", "2a_history": "2a, with history"}
    short = ["bm25", "dense", "llm", "reasonembed", "reranker"]
    rows = []
    for k, x in ab.items():
        keep = [r for r in x["rows"] if "top 100" not in r["stage"] and "not adopted" not in r["stage"]]
        rows.append([r"\multicolumn{5}{l}{\textit{" + esc(names.get(k, k)) + f" (train {x['topics']['train']} / dev "
                     f"{x['topics']['dev']} topics)" + "}}"])
        for i, r in enumerate(keep):
            key = f"abl.{k}.{short[i]}"
            put(key + ".train", r["train"])
            put(key + ".dev", r["dev"])
            put(key + ".dev.ci_lo", r["dev_ci95"][0])
            put(key + ".dev.ci_hi", r["dev_ci95"][1])
            put_ci(key + ".dev_delta", r["dev_minus_prev"])
            put_ci(key + ".train_delta", r["train_minus_prev"])
            rows.append([esc(r["stage"]), f(r["train"]), fci(r["train_minus_prev"]) if r["train_minus_prev"] else "--",
                         fv_ci(r["dev"], r["dev_ci95"]), fci(r["dev_minus_prev"]) if r["dev_minus_prev"] else "--"])
        rows.append("MID")
    table(out, "t2_ablation.tex", "Ablation by stage on the same topics (ReasonEmbed over the hybrid top 50). "
          "$\\Delta$: paired bootstrap difference to the previous stage (topics resampled within domain, 10,000 draws).",
          "tab:app-ablation", "lcccc", ["Stage", "Train", "$\\Delta$ train [95\\% CI]", "Dev [95\\% CI]", "$\\Delta$ dev [95\\% CI]"],
          rows[:-1], star=True)


