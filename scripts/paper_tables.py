def unique_docs(R, pattern, doms, split="dev"):
    out = set()
    for dom in doms:
        p = os.path.join(R, "foreign", "runs", pattern.format(pre=f"t{1 if doms is T1 else 2}_{dom}_{split}"))
        if not os.path.exists(p):
            return None
        with open(p) as fh:
            for ln in fh:
                x = ln.split()
                out.add((dom, x[2]))
    return out


