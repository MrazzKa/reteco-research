def t1_submission(a, R, out):
    fin = jload(os.path.join(R, "final_1116.json"))
    src = "final_1116.json"
    if not fin:
        print("WARNING: final_1116.json missing — falling back to final_1110.json (pre-S1)")
        fin, src = jload(os.path.join(R, "final_1110.json")), "final_1110.json"
    conf = jload(os.path.join(a.root, "configs", "submission.json"))
    mains, fbs, auto = conf["_main_runs"], conf["_fallback_runs"], conf["_auto_2a"]
    unused = {v for k, x in conf.get("_unused_runs", {}).items() if k != "why" for v in x}
    unused |= {"1a_p100", "2a_nomaxp_p100"}
    rowsj = {r["variant"]: r for r in fin["rows"]}
    sub_of = lambda r: "1a" if r["query"] == "1a" else ("1b" if r["query"].startswith("1b") else "2a")

    def role(v):
        if v == auto["with_answers"]:
            return "main"
        if v == auto["without_answers"]:
            return "main if no answers / backup"
        if v in mains.values():
            return "main"
        if any(v in x for x in fbs.values()):
            return "backup"
        return None

    ab = jload(os.path.join(R, "ablation_1110.json"))
    luc = {}
    for t in ("track1_lucene", "track2_lucene"):
        for r in jload(os.path.join(a.root, "research", "runs_v11", t, "results.json")) or []:
            luc[(r["run"], r["domain"])] = r["ndcg10"]
    rows = []
    for sub, (qkey, abl_key, doms, refkey) in {"1a": ("1a", "1a", T1, "1a"), "1b": ("1b", "1b", T1, "1b"),
                                                "2a": (None, "2a_current", T2, "2a_current")}.items():
        # baselines first
        ref_dev = sum(REF[refkey][d][1] for d in doms) / len(doms)
        ref_tr = sum(REF[refkey][d][0] for d in doms) / len(doms)
        put(f"bm25_official.{sub}.dev", ref_dev)
        put(f"bm25_official.{sub}.train_full", ref_tr)
        rows.append([sub, "BM25 (official starter kit)", "baseline", "--", f(ref_dev)])
        b = ab[abl_key]["rows"][0] if ab else None
        if b:
            put(f"bm25_ours.{sub}.train", b["train"])
            put(f"bm25_ours.{sub}.dev", b["dev"])
            put(f"bm25_ours.{sub}.dev.ci_lo", b["dev_ci95"][0])
            put(f"bm25_ours.{sub}.dev.ci_hi", b["dev_ci95"][1])
            rows.append([sub, "BM25 (ours, Lucene analyser)" + (", current turn" if sub == "2a" else ""), "baseline",
                         f(b["train"]), fv_ci(b["dev"], b["dev_ci95"])])
        if sub == "2a":
            ref_dev_h = sum(REF["2a_history"][d][1] for d in doms) / len(doms)
            put("bm25_official.2a_history.dev", ref_dev_h)
            put("bm25_official.2a_history.train_full", sum(REF["2a_history"][d][0] for d in doms) / len(doms))
            rows.append([sub, "BM25 (official), with history", "baseline", "--", f(ref_dev_h)])
            bh = ab["2a_history"]["rows"][0] if ab else None
            if bh:
                put("bm25_ours.2a_history.train", bh["train"])
                put("bm25_ours.2a_history.dev", bh["dev"])
                rows.append([sub, "BM25 (ours), with history", "baseline", f(bh["train"]), fv_ci(bh["dev"], bh["dev_ci95"])])
        sys_rows = sorted([r for r in fin["rows"] if sub_of(r) == sub and r["variant"] not in unused and role(r["variant"])],
                          key=lambda r: (0 if role(r["variant"]) == "main" else 1, -(r["dev"] or 0)))
        for r in sys_rows:
            v = r["variant"]
            put(f"sub.{v}.train", r["train"])
            put(f"sub.{v}.dev", r["dev"])
            put(f"sub.{v}.dev.ci_lo", r["dev_ci95"][0])
            put(f"sub.{v}.dev.ci_hi", r["dev_ci95"][1])
            rows.append([sub, tt(r["run_id"]), role(v), f(r["train"]), fv_ci(r["dev"], r["dev_ci95"])])
        rows.append("MID")
    rows = rows[:-1]
    table(out, "t1_submission.tex", "Submitted runs and baselines. Train: rule-8 subsample ($\\le$30 topics per domain) "
          "on which every choice was made; dev: all topics, 95\\% bootstrap interval of the domain macro. "
          "nDCG@10 (official scorer), macro over domains. Official BM25 train numbers are on the full train split and "
          "are not shown.", "tab:submission", "llllc", ["Task", "Run", "Role", "Train", "Dev [95\\% CI]"], rows,
          note=f"2a main = \\texttt{{UA\\_2a\\_auto}}: {esc(auto['with_answers'])} when earlier answers are present, "
               f"otherwise {esc(auto['without_answers'])}. Source: {esc(src)}.", star=True)
    return src


