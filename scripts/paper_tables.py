# ---------------------------------------------------------------- table 5: compute
def unique_docs(R, pattern, doms, split="dev"):
    out = set()
    for dom in doms:
        p = os.path.join(R, "foreign", "runs", pattern.format(pre=f"t{1 if doms is T1 else 2}_{dom}_{split}"))
        if not os.path.exists(p):
            return None
        with open(p) as fh:
            for ln in fh:
                x = ln.split()
                out.add((dom, x[2]))
    return out


def t5_compute(a, R, out):
    cp = jload(os.path.join(R, "compute_1110.json"))
    c1 = jload(os.path.join(R, "cold_full", "c1_report.json"))
    conf = jload(os.path.join(a.root, "configs", "submission.json"))
    if not cp or not c1:
        return placeholder(out, "t5_compute.tex", "compute_1110.json or cold_full/c1_report.json missing")
    rows = []
    for x in cp["components"]:
        if "A2" in x["stage"] or "rule 18" in x["stage"]:
            continue
        rows.append([esc(x["stage"]), esc(x["model"]), tt(x["revision"]), esc(x["precision"]), esc(x["throughput"])])
    # ---- test-time estimate without pool 100 (arithmetic documented in README.md)
    tm = c1["timing"]
    rws = {r["variant"]: r for r in tm["rows"]}
    rate1 = rws["1a_p100"]["reasonembed_new_docs"] / rws["1a_p100"]["reasonembed_s"]
    rate2 = rws["2a_history"]["reasonembed_new_docs"] / rws["2a_history"]["reasonembed_s"]
    p1a = unique_docs(R, "{pre}_1a_rerun__none.tsv", T1)
    p1b = unique_docs(R, "{pre}_1b_rerun__none.tsv", T1)
    ph = unique_docs(R, "{pre}_2ah_hybrid__none.tsv", T2)
    phq = unique_docs(R, "{pre}_2ahq_h0q__none.tsv", T2)
    pno = unique_docs(R, "{pre}_2a_nomaxp__none.tsv", T2)
    pmx = unique_docs(R, "{pre}_2a_maxp__none.tsv", T2)
    extra_docs = {"1a": len(p1a), "1b": len(p1b - p1a),
                  "2a": len(pno - ph - phq) + len(pmx - ph - phq - pno) - rws["2a_maxp"]["reasonembed_new_docs"]}
    extra_s = {"1a": extra_docs["1a"] / rate1, "1b": extra_docs["1b"] / rate1, "2a": extra_docs["2a"] / rate2}
    per_sub, fixed = {"1a": 0.0, "1b": 0.0, "2a": 0.0}, {"1a": 0.0, "1b": 0.0, "2a": 0.0}
    for v, r in rws.items():
        if v.endswith("_p100"):
            continue
        per_sub[r["sub"]] += r["wall_s"] - r["bm25_index_s"]
        fixed[r["sub"]] += r["bm25_index_s"]
    est = {s: (per_sub[s] + extra_s[s]) * TEST[s] / DEV[s] + fixed[s] for s in per_sub}
    pre = tm["pregenerate_s"]
    pre_test = pre["1"] * (TEST["1a"] + TEST["1b"]) / (DEV["1a"] + DEV["1b"]) + pre["2"] * TEST["2a"] / DEV["2a"]
    total = sum(est.values()) + pre_test
    put("compute.rate_docs_per_s.track1", rate1)
    put("compute.rate_docs_per_s.track2", rate2)
    for s in est:
        put(f"compute.no_p100.extra_reasonembed_docs_dev.{s}", extra_docs[s])
        put(f"compute.no_p100.test_estimate_min.{s}", est[s] / 60)
    put("compute.no_p100.pregen_test_min", pre_test / 60)
    put("compute.no_p100.test_estimate_h", total / 3600)
    put("compute.with_p100.test_estimate_h", tm["test_estimate_s"] / 3600)
    put("compute.c1.wall_h_dev_size", tm["wall_s_total"] / 3600)
    put("compute.p100.reasonembed_docs_dev.1a", rws["1a_p100"]["reasonembed_new_docs"])
    put("compute.p100.reasonembed_s_dev.1a", rws["1a_p100"]["reasonembed_s"])
    put("compute.pool50.unique_docs_dev.1a", len(p1a))
    put("compute.pool50.unique_docs_dev.2a_history", len(ph))
    put("compute.c1.reasonembed_docs_dev.2a_history", rws["2a_history"]["reasonembed_new_docs"])
    rr = conf["variants"]["2a_history_rr"]["llm_rerank"]
    put("compute.reranker.pairs_per_s_c1", rws["2a_history_rr"]["llm_rerank_new_pairs"] / rws["2a_history_rr"]["llm_rerank_s"])
    note = (f"Machine: {esc(cp['machine'])}. Full test without pool 100 (350 1a queries, 820 1b steps, 200 2a turns; "
            f"all caches empty, all submitted runs): $\\approx${total / 3600:.1f}\\,h "
            f"(1a {est['1a'] / 60:.0f}\\,min, 1b {est['1b'] / 60:.0f}\\,min, 2a {est['2a'] / 60:.0f}\\,min, "
            f"LLM pre-generation {pre_test / 60:.0f}\\,min), scaled from the cold dress rehearsal on dev "
            f"({tm['wall_s_total'] / 3600:.1f}\\,h with pool 100; reranker {rr['checkpoint'].split('/')[-1]} "
            f"over the top {rr['depth']}).")
    table(out, "t5_compute.tex", "Models, revisions, precision and measured throughput (one RTX 4060 Laptop GPU, 8\\,GB).",
          "tab:compute", "lp{3.2cm}lp{2.6cm}p{4.2cm}", ["Stage", "Model", "Revision", "Precision", "Throughput"], rows,
          note=note, star=True)
    return {"rate1": rate1, "rate2": rate2, "extra_docs": extra_docs, "extra_s": extra_s, "per_sub": per_sub,
            "fixed": fixed, "est": est, "pre_test": pre_test, "total": total}


