def t7_noise(R, out):
    nd = jload(os.path.join(R, "nondet", "report.json"))
    c1 = jload(os.path.join(R, "cold_full", "c1_report.json"))
    if not nd or not c1:
        return placeholder(out, "t7_noise.tex", "nondet/report.json or cold_full/c1_report.json missing")
    rows = []
    for v in ("1a", "1a_noRE", "1b", "1b_noRE", "2a_history_rr", "2a_history_q", "2a_history", "2a_nomaxp", "2a_maxp"):
        x = c1["runs"].get(v)
        if not x:
            continue
        put(f"noise.c1.{v}.warm", x["research"])
        put(f"noise.c1.{v}.cold", x["official"])
        put_ci(f"noise.c1.{v}.cold_minus_warm", x["cold_minus_warm"])
        rows.append([tt(v), f(x["research"]), f(x["official"]), fci(x["cold_minus_warm"])])
    g = c1["generations"]
    for k, x in g.items():
        put(f"noise.generations.{k}.identical_to_cache", x["identical_to_research_cache"])
        put(f"noise.generations.{k}.n", x["cold"])
        put(f"noise.generations.{k}.identical_to_b3b", x["identical_to_b3b_fresh"])
    for v, x in nd["variants"].items():
        put_ci(f"noise.b3b.{v}.fresh_minus_cached", x["fresh_minus_cached"])
    ident = sum(x["identical_to_research_cache"] for x in g.values())
    tot = sum(x["cold"] for x in g.values())
    put("noise.generations.share_identical_to_cache", ident / tot)
    note = (f"LLM texts of the fresh run identical to the cached ones: {ident:,} of {tot:,} "
            f"({100 * ident / tot:.0f}\\%); identical to a second fresh run over the same input set: "
            f"{sum(x['identical_to_b3b_fresh'] for x in g.values()):,} of {tot:,}. vLLM at temperature 0 is "
            "deterministic for a fixed batch of inputs and changes with batch composition.")
    table(out, "t7_noise.tex", "Run-to-run variation from LLM generation: dev nDCG@10 of each submitted run with the "
          "cached LLM texts (reported numbers) and rebuilt from empty caches (cold dress rehearsal); paired bootstrap.",
          "tab:noise", "lccc", ["Run", "Cached", "Fresh", "Fresh $-$ cached [95\\% CI]"], rows, note=note)


